import {spawn} from 'node:child_process';
import {createWriteStream,readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const repo=fileURLToPath(new URL('../../../../',import.meta.url));
const browser=process.env.HSK_ADAPTER_CI_BROWSER;
if(!['chromium','webkit'].includes(browser))throw Error('Set HSK_ADAPTER_CI_BROWSER to the actual matrix browser');
const [label,cwd,...command]=process.argv.slice(2);
if(!/^[a-z0-9-]+$/.test(label??'')||!['.','course-app','hsk1-app'].includes(cwd)||!command.length)throw Error('Usage: run-command.mjs label .|course-app|hsk1-app command [args]');
const dir=resolve(repo,'course-app/.repro-output/b10-adapter-ci',browser);mkdirSync(dir,{recursive:true});
const logFile=resolve(dir,label+'.log'),startedAt=new Date().toISOString(),log=createWriteStream(logFile);
let spawnError;
const child=spawn(command[0],command.slice(1),{cwd:resolve(repo,cwd),env:process.env,stdio:['ignore','pipe','pipe']});
child.stdout.on('data',bytes=>{process.stdout.write(bytes);log.write(bytes)});
child.stderr.on('data',bytes=>{process.stderr.write(bytes);log.write(bytes)});
child.on('error',error=>{spawnError=error.message;log.write(error.stack+'\n')});
const {code,signal}=await new Promise(resolve=>child.on('close',(code,signal)=>resolve({code,signal})));
await new Promise(resolve=>log.end(resolve));
const bytes=readFileSync(logFile);
writeFileSync(resolve(dir,label+'.command.json'),JSON.stringify({schemaVersion:1,label,browser,command,cwd,startedAt,endedAt:new Date().toISOString(),exitCode:code,signal,spawnError:spawnError??null,log:{file:`course-app/.repro-output/b10-adapter-ci/${browser}/${label}.log`,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')}},null,2)+'\n');
process.exitCode=code===0&&!signal&&!spawnError?0:code||1;

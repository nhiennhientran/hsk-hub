'use strict';
// Source JSON stays editable; this build validates it against the actual textbook data.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const dir=path.resolve(__dirname,'../new-hsk1/hsk1'),ctx={window:{},console};
vm.createContext(ctx);
for(const file of ['new-data.js','new-enrichment.js','textbook-data-corrections.js','textbook-audio-segments.js'])vm.runInContext(fs.readFileSync(path.join(dir,file),'utf8'),ctx);
const bank=['01-05','06-10','11-15'].flatMap(range=>JSON.parse(fs.readFileSync(path.join(dir,'question-bank',`bank-${range}.json`),'utf8')));
const ids=new Set(),kinds=['choice','sort','translation','listening'];
const norm=s=>s.normalize('NFKC').replace(/[\s\p{P}]/gu,'');
assert.equal(bank.length,15);
for(let i=0;i<bank.length;i++){
  const lesson=bank[i];assert.equal(lesson.lesson,i+1);assert.ok(lesson.goal_vi);
  for(const kind of kinds){
    assert.equal(lesson[kind].length,5);
    for(const q of lesson[kind]){
      assert.ok(!ids.has(q.id),`Duplicate ID: ${q.id}`);ids.add(q.id);q.kind=kind;q.lesson=lesson.lesson;
      assert.ok(q.prompt&&q.explanation&&q.skill,`${q.id}: missing instruction or explanation`);
      assert.ok(!/(?:câu|đáp án|lựa chọn)\s+(?:cuối|đầu tiên)|Các (?:lựa chọn|câu) (?:khác|còn lại) lần lượt|đáp án [ABCD]\b/i.test(q.explanation),`${q.id}: position-dependent explanation`);
      if(kind==='sort'){
        assert.ok(q.tokens.length>=2&&q.answers.length);const tokens=[...norm(q.tokens.join(''))].sort().join('');
        for(const a of q.answers)assert.equal([...norm(a)].sort().join(''),tokens,`${q.id}: mismatched answer tokens`);
      }else{
        assert.equal(q.options.length,4);assert.equal(new Set(q.options.map(x=>x.normalize("NFKC").trim())).size,4,`${q.id}: duplicate options`);assert.ok(Number.isInteger(q.answer)&&q.answer>=0&&q.answer<4);
      }
      if(kind==='listening'){
        const audio=q.audio,track=audio.track.match(/^(\d+)-([135])$/);assert.ok(track);assert.equal(+track[1],lesson.lesson);
        const line=ctx.window.HSK1_LESSONS[i].scenes[(+track[2]-1)/2].lines[audio.line];
        assert.equal(q.transcript,line.zh,`${q.id}: audio transcript mismatch`);
        const times=ctx.window.HSK1_OFFICIAL_SEGMENTS.text[audio.track][audio.line];
        assert.ok(times&&times[0]>=0&&times[1]>times[0]);[audio.start,audio.end]=times;
        // Pinyin in the source bank is editorially checked and may correct the legacy site.
        assert.ok(q.pinyin);
      }
    }
  }
}
assert.equal(ids.size,300);
const output='// Generated by node tools/build-learning-bank.cjs. Edit question-bank/*.json instead.\nwindow.HSK1_NEW_BANK = '+JSON.stringify(bank,null,2)+';\n';
const target=path.join(dir,'learning-bank.js');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),output,'Rebuild learning-bank.js after editing sources');
else fs.writeFileSync(target,output);
console.log('Validated 15 lessons, 300 questions, 75 original-audio mappings.');
